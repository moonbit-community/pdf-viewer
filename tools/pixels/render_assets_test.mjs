import assert from 'node:assert/strict';
import {PdfRenderAssets} from '../../web/pdf-render-assets.mjs';
let loads=0,closes=0;
const loadImage=async uri=>{loads++;return {width:uri==='large'?100:2,height:2,close(){closes++;}};};
const assets=new PdfRenderAssets({maxBytes:100,maxEntries:2,loadImage});
const [first,second]=await Promise.all([assets.acquire('a'),assets.acquire('a')]);
assert.equal(first,second);assert.equal(loads,1);
assets.release(first);assert.equal(closes,0);assets.release(second);
assert.equal(await assets.acquire('a'),first);assets.release(first);assert.equal(loads,1);
const oversized=await assets.acquire('large');assert.equal(assets.bytes,18);
assets.release(oversized);assert.equal(closes,1,'An oversized lease is released without corrupting another entry accounting');
const held=await assets.acquire('a');
const b=await assets.acquire('b');assets.release(b);
const c=await assets.acquire('c');assets.release(c);
assert.ok(assets.entries.has('a'),'Eviction cannot close an active consumer');
assets.dispose();assert.equal(assets.bytes,0);assert.equal(closes,3);
assets.release(held);assert.equal(closes,4,'The active bitmap closes once after the document is disposed');
let resolveImage;
const pending=new PdfRenderAssets({loadImage:()=>new Promise(resolve=>{resolveImage=resolve;})});
const acquisition=pending.acquire('pending');pending.dispose();
resolveImage({width:2,height:2,close(){closes++;}});
const value=await acquisition;assert.equal(closes,4);pending.release(value);assert.equal(closes,5);
assert.equal(pending.entries.size,0);assert.equal(pending.bytes,0);
const failed=new PdfRenderAssets({loadImage:async()=>{throw Error('Decode failed');}});
await assert.rejects(failed.acquire('bad'),/Decode failed/);assert.equal(failed.entries.size,0);
console.log('Render assets: shared acquisition, reuse, accounting, bounded eviction, active and pending disposal passed.');
